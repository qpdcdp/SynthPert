    parser.add_argument("--limit_groups", type=int, default=0, help="Limit the number of (cell_type, perturbation) groups. 0 for all.")
    parser.add_argument("--lora_checkpoint", type=str, default=None, help="Path to LoRA checkpoint for the model(s).")
    parser.add_argument("--cell_line", type=str, default="none")
    parser.add_argument("--dataset_fraction", type=float, default=1.0)
    parser.add_argument("--chunk_size", type=int, default=32, help="Size of each chunk for batched generation.")
    parser.add_argument("--generation_temperature", type=float, default=0.8, help="Temperature for initial prediction sampling.")
    parser.add_argument("--revision_temperature", type=float, default=0.4, help="Temperature for revision generation sampling.")
    parser.add_argument("--max_tokens", type=int, default=8192, help="Maximum number of new tokens for generation.")
    parser.add_argument("--generate_all_non_de_samples", action="store_true")
    parser.add_argument("--generate_4x_non_de_samples", action="store_true")

    args = parser.parse_args()
    main(args)